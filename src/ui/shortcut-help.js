/** پنجرهٔ راهنمای میان‌برهای صفحه‌کلید (کلید ?). */

import { el } from '../core/dom.js';
import { openDialog } from './dialog.js';

const SHORTCUTS = [
  ['Ctrl + K', 'پالت فرمان — همه‌چیز از یک جا'],
  ['/', 'رفتن به نوار جست‌وجو'],
  ['۱ … ۹', 'جابه‌جایی بین زبانه‌های پنل کناری'],
  ['T', 'تغییر تم روشن و تیره'],
  ['H', 'حالت پنهان: اعداد مالی و یادداشت‌ها محو می‌شوند (نگه داشتن موس = نمایش)'],
  ['?', 'همین راهنما'],
  ['Esc', 'بستن پنجره یا پیشنهادها'],
  ['← →', 'پیمایش زبانه‌ها و روزهای تقویم'],
  ['!y عبارت', 'جست‌وجوی یک‌باره در یوتیوب (!w ویکی‌پدیا، !t ترب، !dk دیجی‌کالا، !g گوگل)'],
  ['۲۵×۴ یا ۱۰۰ دلار', 'حساب و تبدیل فوری داخل نوار جست‌وجو'],
  ['دوبار کلیک', 'ویرایش یک کار، یا افزودن یادداشت روی روز تقویم'],
  ['کشیدن یا Alt + ← →', 'جابه‌جا کردن میان‌برها؛ کشیدن یک پیوند از بیرون، میان‌بر می‌سازد'],
  ['yar + فاصله', 'در نوار آدرس کروم: حساب، تبدیل ارز، «کار …» یا «یادداشت …» — حتی وقتی تب جدید باز نیست'],
  ['راست‌کلیک', 'روی متن: افزودن به کارها یا یادداشت؛ روی پیوند یا صفحه: افزودن به میان‌برها'],
];

export function openShortcutHelp() {
  if (document.querySelector('.dialog--help')) return;
  const content = el(
    'dl',
    { class: 'help' },
    SHORTCUTS.flatMap(([keys, description]) => [
      el('dt', {}, [el('kbd', { text: keys })]),
      el('dd', { text: description }),
    ]),
  );
  openDialog({ title: 'میان‌برهای صفحه‌کلید', iconName: 'keyboard', content, className: 'dialog--help' });
}
